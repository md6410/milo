# -*- coding: utf-8 -*-
"""پروژهٔ «فروشگاهِ Weby» — کلِ سایت به‌صورتِ بخش‌های کلی که از ماژول‌های کتابخانه ساخته شده‌اند."""
from dsl import Doc, P, use
from proj import load, place, finish_area
from wattach import attach, NEW_AREAS

NAME = 'فروشگاه‌ساز Weby'
SUMMARY = ('کلِ فروشگاهِ آنلاین Weby (فروشگاه، انبار، پرداخت، ارسال، پیامک…) به‌شکل یک پروژهٔ Milo: '
           'هر بخش‌کلی از ماژول‌های کتابخانه ساخته شده و وابستگی‌های میان‌بخشی با پورت‌هایشان کشیده شده است.')
SLUG = 'p-weby'
TITLE = 'Weby — فروشگاه‌سازِ کامل'


def build():
    d = Doc('wb')
    m03 = load('m03_payments')

    # ===== ۱) کاتالوگ و فروشندگان
    A1 = d.area('کاتالوگ و فروشندگان', icon='🛍️', color='#7c3aed',
                summary='کالا و ترکیب‌ها، قیمتِ نهایی، فروشنده‌های چندگانه، قیمتِ همکاری و اتصال به ترب',
                details='هر چیزی که مشتری می‌بیند و قیمتش: کالا (واحد/ترکیب/کدِ یکتا)، فروشنده (امانی/خریداری)، همکارِ فروش (گرید) و ترب (API/وبهوک).')
    P_ = place(A1, load('m10_product').make, 'کالا، قیمت و واحد')
    S_ = place(A1, load('m11_seller').make, 'فروشنده (چندفروشنده و امانی)')
    SP = place(A1, load('m12_partner').make, 'همکارِ فروش (گرید و قیمتِ همکاری)')
    T_ = place(A1, load('m04_torob').make, 'اتصال به ترب (API، وبهوک، انتسابِ فروش)')
    A1.link(P_, 'کالای قابلِ فروش', SP, 'سبدِ همکار', 'قیمتِ نهاییِ مصرف‌کننده')
    A1.link(P_, 'کالای قابلِ فروش', T_, 'کاتالوگِ فروشگاه', 'قیمت و موجودی برای ترب')
    A1.link(P_, 'کدهای کالا', S_, 'پیوندِ کالا و فروشنده', 'کدِ پایه برای پیوند')
    A1.expose_out('کالای قابلِ فروش', 'کالای منتشرشده با قیمتِ نهایی و موجودی', P_, 'کالای قابلِ فروش')
    A1.expose_out('کدهای کالا', 'کدِ خانواده/پایه/SKU برای انبار و برچسب', P_, 'کدهای کالا')
    A1.expose_out('قیمتِ همکاری', 'قیمتِ هر ردیف برای همکار', SP, 'قیمتِ همکاری')
    A1.expose_out('فروشندهٔ انتخاب‌شده', 'فروشنده‌ای که قلم را می‌فروشد', S_, 'فروشندهٔ انتخاب‌شده')
    A1.expose_in('سفارشِ ثبت‌شده', 'سفارشِ تازه برای قفلِ سهمِ فروشنده و انتسابِ ترب', [(S_, 'سفارشِ ثبت‌شده'), (T_, 'سفارشِ ثبت‌شده')],
                 use='از «سبد، تسویه‌حساب و چرخهٔ سفارش»')
    finish_area(A1)

    # ===== ۲) سفارش و پرداخت
    A2 = d.area('سفارش و پرداخت', icon='🧺', color='#dc2626',
                summary='سبد ← تسویه ← پرداخت (هسته + درگاه‌ها) ← چرخهٔ سفارش',
                details='قلبِ فروشگاه. درگاه‌ها ماژول‌های جدایند و هسته با یک قرارداد صدایشان می‌زند؛ پرداخت و سفارش هر دو در یک چرخهٔ دوطرفه‌اند (سفارش پرداخت می‌خواهد، پرداخت نتیجه را به سفارش برمی‌گرداند).')
    O = place(A2, load('m14_order').make, 'سبد، تسویه‌حساب و چرخهٔ سفارش')
    PC = place(A2, m03.core, 'هستهٔ پرداختِ آنلاین')
    gws = []
    for key, gwm in (('zarinpal', m03.ZARIN), ('saman', m03.SAMAN), ('mellat', m03.MELLAT), ('jibit', m03.JIBIT),
                     ('snapppay', m03.SNAPP), ('digipay', m03.DIGI), ('cod', m03.COD)):
        mk, bd = gwm
        title = bd()[2]
        gws.append((key, place(A2, mk, title)))
    A2.link(O, 'سفارشِ ثبت‌شده', PC, 'درخواستِ پرداخت', 'سفارشِ آمادهٔ پرداخت')
    for key, g in gws:
        A2.link(O, 'سفارشِ ثبت‌شده', g, 'درخواستِ شروعِ درگاه', 'اگر مشتری این روش را برگزید')
        A2.link(g, 'نشانیِ انتقال به درگاه', PC, 'نشانیِ تراکنشِ درگاه', 'پاسخِ start')
        A2.link(g, 'نتیجهٔ تأیید', PC, 'نتیجهٔ تأییدِ درگاه', 'پاسخِ verify')
    A2.link(PC, 'نتیجهٔ پرداخت', O, 'نتیجهٔ پرداخت', 'پرداخت تأیید/رد شد', two=True)
    A2.expose_in('تنظیماتِ درگاه‌ها', 'کلیدها و حالتِ آزمایشی/واقعیِ هر درگاه',
                 [(PC, 'تنظیماتِ درگاه‌ها')] + [(g, 'تنظیماتِ درگاه') for k, g in gws if k != 'cod'])
    A2.expose_in('بازگشتِ بانک', 'پارامترهای بازگشتِ مشتری از درگاه',
                 [(PC, 'بازگشتِ درگاه')] + [(g, 'بازگشتِ درگاه') for k, g in gws])
    A2.expose_out('سفارشِ ثبت‌شده', 'سفارشِ ثبت‌شده با قیمتِ قفل‌شده', O, 'سفارشِ ثبت‌شده')
    A2.expose_out('وضعیتِ سفارش', 'pending → paid → … → delivered', O, 'وضعیتِ سفارش')
    A2.expose_out('نشانیِ انتقال به درگاه', 'redirect/فرمِ POST برای فرستادنِ مشتری به بانک', PC, 'نشانیِ انتقال به درگاه')
    finish_area(A2)

    # ===== ۳) انبار و چاپ
    A3 = d.area('انبار و چاپ', icon='🏭', color='#b45309',
                summary='انبارِ چندگانه با کدِ دانه، اسکنِ QR/بارکد، برچسب و چاپگرِ مرکزی',
                details='همه‌چیزِ فیزیکی: کالا می‌رسد، کد می‌گیرد، برچسب می‌خورد و با اسکن وارد/خارج می‌شود.')
    W = place(A3, load('m09_warehouse').make, 'انبارِ چندگانه با کدِ دانه')
    Q = place(A3, load('m01_scanner').make, 'خواندنِ QR و بارکد')
    L = place(A3, load('m08_labels').make, 'ساخت و چاپِ برچسب')
    PS = place(A3, load('m07_printer').make, 'چاپگر مرکزی (ایستگاهِ چاپ)')
    A3.link(Q, 'کدِ تمیزشده', W, 'اسکنِ انباردار', 'کدِ اسکن‌شده')
    A3.link(L, 'کارِ چاپ', PS, 'درخواستِ چاپ', 'برچسب برای چاپ')
    A3.expose_in('تعریفِ کالا و انبار', 'کدهای کالا، دسته، فروشنده، مالکیت و انبار', [(W, 'تعریفِ کالا و انبار')])
    A3.expose_in('سفارشِ برای خروج', 'سفارشِ پرداخت‌شده برای اسکنِ خروج', [(W, 'سفارشِ برای خروج')])
    A3.expose_out('سفارشِ بسته‌شده', 'سفارشی که اقلامش اسکن و خارج شد', W, 'سفارشِ بسته‌شده')
    A3.expose_out('موجودیِ زنده', 'موجودیِ هر محموله/دانه و مجموعِ همهٔ انبارها', W, 'موجودیِ زنده')
    finish_area(A3)

    # ===== ۴) نقشه و نشانی
    A4 = d.area('نقشه و نشانی', icon='🗺️', color='#0ea5e9',
                summary='نقشه و نشان، جست‌وجوی نشانی، فاصله و نقشهٔ پوشش',
                details='زنجیرهٔ سرویس‌های نقشه با جایگزینِ داخلی؛ مسیرِ کاربر هرگز به شبکه نمی‌زند مگر با دکمه.')
    M = place(A4, load('m02_map').make, 'نقشه و نشان')
    A4.expose_out('نقطهٔ انتخاب‌شده', 'مختصات و نشانیِ متنیِ انتخاب‌شده برای نشانیِ مشتری', M, 'نقشه و نقطهٔ انتخاب‌شده')
    finish_area(A4)

    # ===== ۵) ارسال
    A5 = d.area('ارسال', icon='🚚', color='#2563eb',
                summary='میزِ ارسال و حامل‌ها: پیک، اسنپ، تیپاکس، پست، حضوری',
                details='تصمیمِ «چه کسی ببرد» یک‌جا؛ حامل‌ها مستقل‌اند و همدیگر را نمی‌شناسند.')
    SD = place(A5, load('m13_shipping').make, 'میزِ ارسال و حامل‌ها')
    A5.expose_in('سفارشِ خارج‌شده از انبار', 'سفارشِ اسکن‌شده و بسته‌شده', [(SD, 'سفارشِ خارج‌شده از انبار')])
    A5.expose_out('کارِ ارسال', 'وضعیتِ ارسال برای سفارش', SD, 'کارِ ارسال')
    finish_area(A5)

    # ===== ۶) ورود و پیامک
    A6 = d.area('ورود و پیامک', icon='💬', color='#4f46e5',
                summary='ورودِ بی‌رمز با OTP/Passkey/کپچا و ارسالِ پیامک با SMS.IR',
                details='کدِ ورود از همان گلوگاهِ پیامک می‌رود؛ اعلان‌های سفارش هم همان‌جا.')
    SM = place(A6, load('m05_sms').make, 'ارسال پیامک با SMS.IR')
    AU = place(A6, load('m15_auth').make, 'ورودِ بی‌رمز (OTP، Passkey، کپچا)')
    A6.link(SM, 'کدِ تأییدشده', AU, 'کدِ پیامکی', 'کدِ درست بود')
    A6.expose_in('درخواستِ ورود', 'موبایل و هدفِ ورود', [(AU, 'درخواستِ ورود'), (SM, 'درخواستِ کدِ ورود')])
    A6.expose_in('رویدادِ سفارش', 'ثبت/تغییرِ وضعیتِ سفارش برای اعلان', [(SM, 'رویدادِ سفارش')])
    A6.expose_out('نشستِ واردشده', 'کاربرِ واردشده با موبایلِ تأییدشده', AU, 'نشستِ واردشده')
    finish_area(A6)

    # ===== ۷) مالی و فاکتور
    A7 = d.area('مالی و فاکتور', icon='🧾', color='#0f766e',
                summary='فاکتورِ سفارش، لینکِ پرداخت و فاکتورِ دستی',
                details='شمارهٔ فاکتور فقط از حسابداری صادر می‌شود؛ مالیات ٪ ثابت؛ فاکتورِ دستی با شناسهٔ منفی در پرداخت.')
    IB = place(A7, load('m06_invoice').make, 'فاکتورساز (پیش‌فاکتور، فاکتور، فاکتور رسمی)')
    A7.expose_in('سفارش برای فاکتور', 'سفارشِ ثبت‌شده که فاکتورش صادر می‌شود', [(IB, 'اطلاعاتِ سند')])
    finish_area(A7)

    # ===== ۸) زیرساخت
    A8 = d.area('زیرساخت و گسترش', icon='🧬', color='#0891b2',
                summary='موتورِ ماژول و قالب (قلاب‌ها) که همهٔ بخش‌ها روی آن می‌نشینند',
                details='هسته ماژول و قالب را نمی‌شناسد؛ افزودنِ امکان یعنی ثبتِ قلاب و یک ردیف در features.php.')
    EE = place(A8, load('m16_extension').make, 'موتورِ ماژول و قالب (مثلِ وردپرس)')
    finish_area(A8)

    # ===== وابستگی‌های میان‌بخشی (به ترتیبِ DAG، سپس بازخوردهای دوطرفه)
    d.link(A1, 'کالای قابلِ فروش', A2, 'کالاهای سبد', 'قیمتِ نهایی و موجودی')
    d.link(A1, 'قیمتِ همکاری', A2, 'کالاهای سبد', 'قیمتِ همکار برای همکار')
    d.link(A1, 'کدهای کالا', A3, 'تعریفِ کالا و انبار', 'کدِ پایه برای انبار')
    d.link(A2, 'سفارشِ ثبت‌شده', A3, 'سفارشِ برای خروج', 'پس از پرداخت')
    d.link(A3, 'سفارشِ بسته‌شده', A5, 'سفارشِ خارج‌شده از انبار', 'آمادهٔ ارسال')
    d.link(A2, 'سفارشِ ثبت‌شده', A7, 'سفارش برای فاکتور', 'صدورِ فاکتور')
    d.link(A4, 'نقطهٔ انتخاب‌شده', A2, 'مشتری و نشانی', 'نشانیِ مشتری')
    d.link(A6, 'نشستِ واردشده', A2, 'مشتری و نشانی', 'کاربرِ تأییدشده')
    d.link(A2, 'سفارشِ ثبت‌شده', A1, 'سفارشِ ثبت‌شده', 'قفلِ سهمِ فروشنده و انتسابِ ترب', two=True)
    d.link(A2, 'وضعیتِ سفارش', A6, 'رویدادِ سفارش', 'اعلانِ پیامکی', two=True)
    d.link(A3, 'سفارشِ بسته‌شده', A2, 'رویدادِ انبار و ارسال', 'خروج از انبار', two=True)
    d.link(A5, 'کارِ ارسال', A2, 'رویدادِ انبار و ارسال', 'تحویل/ناموفق', two=True)
    # ===== بخش‌های کلیِ تکمیلی + تست‌های واقعیِ Weby
    areas = {'catalog': A1, 'order': A2, 'infra': A8}
    for key, (t, ic, col, sm) in NEW_AREAS.items():
        areas[key] = d.area(t, icon=ic, color=col, summary=sm, details=sm + ' — ماژول‌های این بخش از روی آزمون‌های واقعیِ Weby ساخته شده‌اند.')
    by_title = {n.title: n for n in d.nodes if n.kind == 'module'}
    n = attach(d, by_title, areas)
    print('   تست‌های Weby:', n)
    return d, SLUG, TITLE
