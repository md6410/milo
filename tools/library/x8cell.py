from dsl import P, T, S, chain_module


def find(node, title):
    """گرهِ زیرمجموعه با این عنوان (جست‌وجوی عمقی) — برای افزودنِ تست به کارها."""
    stack = list(node.children)
    while stack:
        c = stack.pop(0)
        if c.title == title:
            return c
        stack.extend(c.children)
    raise KeyError(title)


