def lib(area, name):
    """نمونه‌ای از ماژولِ کتابخانه (کپی با src_name)."""
    m = load(name)
    return place(area, m.make, m.TITLE)


def new(area, fn):
    """ماژولِ تازهٔ 8CELL (نه نمونهٔ کتابخانه)."""
    return fn(area.doc, area, None)


